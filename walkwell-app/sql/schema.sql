-- =====================================================================
-- Walking Application - Oracle Database Schema
-- Tables: signup_dtls (user profile) , login_dtls (login audit log)
-- Passwords are stored as bcrypt hashes (irreversible, industry standard)
-- =====================================================================

-- ---------------------------------------------------------------------
-- signup_dtls : one row per registered user
-- ---------------------------------------------------------------------
CREATE TABLE signup_dtls (
    USER_ID          VARCHAR2(50)   NOT NULL,
    NAME             VARCHAR2(100)  NOT NULL,
    PASSWORD_HASH    VARCHAR2(255)  NOT NULL,   -- bcrypt hash (never plaintext)
    CREATED_DATE     DATE           DEFAULT SYSDATE NOT NULL,
    CREATED_TIME     VARCHAR2(15)   DEFAULT TO_CHAR(SYSDATE,'HH24:MI:SS') NOT NULL,
    LAST_LOGIN_DATE  DATE,
    LAST_LOGIN_TIME  VARCHAR2(15),
    IS_ACTIVE        NUMBER(1)      DEFAULT 1 NOT NULL,
    FAILED_ATTEMPTS  NUMBER(4)      DEFAULT 0 NOT NULL,
    LOCKED_UNTIL     DATE,
    CONSTRAINT PK_SIGNUP_DTLS PRIMARY KEY (USER_ID)
);

-- ---------------------------------------------------------------------
-- login_dtls : one row per login event (audit trail)
-- ---------------------------------------------------------------------
CREATE TABLE login_dtls (
    LOGIN_ID      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    USER_ID       VARCHAR2(50)  NOT NULL,
    LOGIN_DATE    DATE          DEFAULT SYSDATE NOT NULL,
    LOGIN_TIME    VARCHAR2(15)  DEFAULT TO_CHAR(SYSDATE,'HH24:MI:SS') NOT NULL,
    IP_ADDRESS    VARCHAR2(45),
    STATUS        VARCHAR2(20)  NOT NULL,   -- SUCCESS / FAILED / LOCKED
    USER_AGENT    VARCHAR2(255),
    CREATED_DATE  DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_LOGIN_DTLS PRIMARY KEY (LOGIN_ID),
    CONSTRAINT FK_LOGIN_USER FOREIGN KEY (USER_ID)
        REFERENCES signup_dtls (USER_ID)
);

-- ---------------------------------------------------------------------
-- Sequence emulator for login_dtls.LOGIN_ID.
-- Atomic UPDATE ... RETURNING provides unique, concurrency-safe IDs.
-- (A real CREATE SEQUENCE requires privileges the app DB user lacks.)
-- ---------------------------------------------------------------------
CREATE TABLE id_counter (
    SEQ_NAME   VARCHAR2(50)  NOT NULL,
    NEXT_VAL   NUMBER        NOT NULL,
    CONSTRAINT PK_ID_COUNTER PRIMARY KEY (SEQ_NAME)
);

INSERT INTO id_counter (SEQ_NAME, NEXT_VAL) VALUES ('LOGIN_DTLS', 1);

-- Helpful indexes
CREATE INDEX IDX_LOGIN_USER_ID   ON login_dtls (USER_ID);
CREATE INDEX IDX_LOGIN_DATE      ON login_dtls (LOGIN_DATE);
CREATE INDEX IDX_SIGNUP_NAME     ON signup_dtls (NAME);

COMMIT;